use std::{
    fs,
    path::{Path, PathBuf},
};

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::{AtomicWriteResult, StateError, content_fingerprint, write_atomically};

pub const GENERATED_MANIFEST_SCHEMA_VERSION: u32 = 1;

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum GeneratedFileChangeKind {
    Create,
    Update,
    Unchanged,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct GeneratedFileChange {
    pub path: PathBuf,
    pub kind: GeneratedFileChangeKind,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub current_sha256: Option<String>,
    pub desired_sha256: String,
    pub diff: String,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct GeneratedManifest {
    pub schema_version: u32,
    pub selection: String,
    pub environment: String,
    pub generated_config_file: String,
    pub content_sha256: String,
    pub selection_sha256: String,
    pub registry_sha256: String,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedConfigArtifact {
    contents: String,
    manifest: GeneratedManifest,
}

impl GeneratedConfigArtifact {
    pub fn new(
        selection: &str,
        compiled_toml: &str,
        selection_source: &[u8],
        registry_sources: &[&[u8]],
    ) -> Result<Self, StateError> {
        validate_selection_name(selection)?;

        let environment = format!("powermise-{selection}");
        let selection_sha256 = content_fingerprint(selection_source);
        let registry_sha256 = fingerprint_sources(registry_sources);
        let compiled_toml = compiled_toml.trim_end();
        let contents = format!(
            "# Generated by Powermise. Source selection: {selection}. Do not edit.\n\
# selection_sha256 = \"{selection_sha256}\"\n\
# registry_sha256 = \"{registry_sha256}\"\n\n\
{compiled_toml}\n"
        );
        let manifest = GeneratedManifest {
            schema_version: GENERATED_MANIFEST_SCHEMA_VERSION,
            selection: selection.into(),
            environment: environment.clone(),
            generated_config_file: format!("config.{environment}.toml"),
            content_sha256: content_fingerprint(contents.as_bytes()),
            selection_sha256,
            registry_sha256,
        };

        Ok(Self { contents, manifest })
    }

    pub fn contents(&self) -> &str {
        &self.contents
    }

    pub fn manifest(&self) -> &GeneratedManifest {
        &self.manifest
    }

    pub fn config_path(&self, mise_config_directory: &Path) -> PathBuf {
        mise_config_directory.join(&self.manifest.generated_config_file)
    }

    pub fn manifest_path(&self, generated_directory: &Path) -> PathBuf {
        generated_directory.join(format!("{}.manifest.json", self.manifest.selection))
    }

    pub fn write_config(
        &self,
        mise_config_directory: &Path,
    ) -> Result<AtomicWriteResult, StateError> {
        write_atomically(
            &self.config_path(mise_config_directory),
            self.contents.as_bytes(),
        )
    }

    pub fn write_manifest(
        &self,
        generated_directory: &Path,
    ) -> Result<AtomicWriteResult, StateError> {
        let path = self.manifest_path(generated_directory);
        let mut contents =
            serde_json::to_vec_pretty(&self.manifest).map_err(|source| StateError::Json {
                operation: "serialize generated manifest",
                path: path.clone(),
                source,
            })?;
        contents.push(b'\n');
        write_atomically(&path, &contents)
    }
}

fn validate_selection_name(selection: &str) -> Result<(), StateError> {
    let valid = !selection.is_empty()
        && selection.split('-').all(|segment| {
            !segment.is_empty()
                && segment
                    .bytes()
                    .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit())
        });

    if valid {
        Ok(())
    } else {
        Err(StateError::InvalidSelectionName {
            selection: selection.into(),
        })
    }
}

pub fn inspect_generated_file(
    path: &Path,
    desired_contents: &[u8],
) -> Result<GeneratedFileChange, StateError> {
    let current_contents = match fs::read(path) {
        Ok(contents) => Some(contents),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => None,
        Err(source) => {
            return Err(StateError::Io {
                operation: "read generated configuration",
                path: path.to_path_buf(),
                source,
            });
        }
    };
    let kind = match current_contents.as_deref() {
        None => GeneratedFileChangeKind::Create,
        Some(current) if current == desired_contents => GeneratedFileChangeKind::Unchanged,
        Some(_) => GeneratedFileChangeKind::Update,
    };

    Ok(GeneratedFileChange {
        path: path.to_path_buf(),
        kind,
        current_sha256: current_contents.as_deref().map(content_fingerprint),
        desired_sha256: content_fingerprint(desired_contents),
        diff: render_diff(path, current_contents.as_deref(), desired_contents, kind),
    })
}

fn render_diff(
    path: &Path,
    current_contents: Option<&[u8]>,
    desired_contents: &[u8],
    kind: GeneratedFileChangeKind,
) -> String {
    if kind == GeneratedFileChangeKind::Unchanged {
        return String::new();
    }

    let current = current_contents
        .map(String::from_utf8_lossy)
        .unwrap_or_default();
    let desired = String::from_utf8_lossy(desired_contents);
    let mut diff = format!("--- {}\n+++ {}\n", path.display(), path.display());
    for (prefix, line) in line_diff(&current, &desired) {
        diff.push(prefix);
        diff.push_str(line);
        diff.push('\n');
    }
    diff
}

/// Renders a longest-common-subsequence line diff, marking added, removed, and
/// common lines so readers see exactly what changes.
fn line_diff<'a>(current: &'a str, desired: &'a str) -> Vec<(char, &'a str)> {
    let current_lines = current.lines().collect::<Vec<_>>();
    let desired_lines = desired.lines().collect::<Vec<_>>();
    let n = current_lines.len();
    let m = desired_lines.len();

    let mut table = vec![vec![0usize; m + 1]; n + 1];
    for i in (0..n).rev() {
        for j in (0..m).rev() {
            table[i][j] = if current_lines[i] == desired_lines[j] {
                table[i + 1][j + 1] + 1
            } else {
                table[i + 1][j].max(table[i][j + 1])
            };
        }
    }

    let mut result = Vec::new();
    let (mut i, mut j) = (0usize, 0usize);
    while i < n && j < m {
        if current_lines[i] == desired_lines[j] {
            result.push((' ', current_lines[i]));
            i += 1;
            j += 1;
        } else if table[i + 1][j] >= table[i][j + 1] {
            result.push(('-', current_lines[i]));
            i += 1;
        } else {
            result.push(('+', desired_lines[j]));
            j += 1;
        }
    }
    while i < n {
        result.push(('-', current_lines[i]));
        i += 1;
    }
    while j < m {
        result.push(('+', desired_lines[j]));
        j += 1;
    }
    result
}

fn fingerprint_sources(sources: &[&[u8]]) -> String {
    let mut digest = Sha256::new();
    for source in sources {
        digest.update(source.len().to_le_bytes());
        digest.update(source);
    }
    format!("{:x}", digest.finalize())
}

#[cfg(test)]
mod tests {
    use std::{
        fs,
        path::PathBuf,
        process,
        sync::atomic::{AtomicU64, Ordering},
        time::{SystemTime, UNIX_EPOCH},
    };

    use super::*;

    static TEST_DIRECTORY_SEQUENCE: AtomicU64 = AtomicU64::new(0);

    struct TestDirectory(PathBuf);

    impl TestDirectory {
        fn new() -> Self {
            let timestamp = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap_or_default()
                .as_nanos();
            let sequence = TEST_DIRECTORY_SEQUENCE.fetch_add(1, Ordering::Relaxed);
            let path = std::env::temp_dir().join(format!(
                "powermise-generated-test-{}-{timestamp}-{sequence}",
                process::id(),
            ));
            fs::create_dir_all(&path).expect("test directory should be created");
            Self(path)
        }
    }

    impl Drop for TestDirectory {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn artifact_has_deterministic_headers_paths_and_fingerprints() {
        let artifact = GeneratedConfigArtifact::new(
            "engineering-agents",
            "[tools]\nnode = \"24\"\n",
            b"selection",
            &[b"harnesses", b"tools"],
        )
        .expect("artifact should compile");

        assert_eq!(
            artifact.contents(),
            format!(
                "# Generated by Powermise. Source selection: engineering-agents. Do not edit.\n\
# selection_sha256 = \"{}\"\n\
# registry_sha256 = \"{}\"\n\n\
[tools]\nnode = \"24\"\n",
                content_fingerprint(b"selection"),
                fingerprint_sources(&[b"harnesses", b"tools"]),
            )
        );
        assert_eq!(
            artifact.manifest().content_sha256,
            content_fingerprint(artifact.contents().as_bytes())
        );
        assert_eq!(
            artifact.config_path(Path::new("mise")),
            Path::new("mise/config.powermise-engineering-agents.toml")
        );
        assert_eq!(
            artifact.manifest_path(Path::new("generated")),
            Path::new("generated/engineering-agents.manifest.json")
        );
    }

    #[test]
    fn artifact_rejects_unsafe_selection_names() {
        for selection in [
            "",
            "Engineering",
            "../escape",
            "two--hyphens",
            "spaces here",
        ] {
            assert!(matches!(
                GeneratedConfigArtifact::new(selection, "", b"", &[]),
                Err(StateError::InvalidSelectionName { .. })
            ));
        }
    }

    #[test]
    fn artifact_config_and_manifest_converge_on_repeat_write() {
        let directory = TestDirectory::new();
        let artifact = GeneratedConfigArtifact::new(
            "engineering-agents",
            "[tools]\nnode = \"24\"\n",
            b"selection",
            &[b"registry"],
        )
        .expect("artifact should compile");

        assert_eq!(
            artifact
                .write_config(&directory.0.join("mise"))
                .expect("config write should succeed"),
            AtomicWriteResult::Created
        );
        assert_eq!(
            artifact
                .write_manifest(&directory.0.join("generated"))
                .expect("manifest write should succeed"),
            AtomicWriteResult::Created
        );
        assert_eq!(
            artifact
                .write_config(&directory.0.join("mise"))
                .expect("repeat config write should succeed"),
            AtomicWriteResult::Unchanged
        );
        assert_eq!(
            artifact
                .write_manifest(&directory.0.join("generated"))
                .expect("repeat manifest write should succeed"),
            AtomicWriteResult::Unchanged
        );

        let manifest: GeneratedManifest = serde_json::from_slice(
            &fs::read(artifact.manifest_path(&directory.0.join("generated")))
                .expect("manifest should exist"),
        )
        .expect("manifest should parse");
        assert_eq!(manifest, artifact.manifest().clone());
    }
    #[test]
    fn inspection_reports_create_update_and_unchanged_without_writing() {
        let directory = TestDirectory::new();
        let path = directory.0.join("config.powermise-test.toml");

        let create = inspect_generated_file(&path, b"desired\n").expect("inspection should work");
        assert_eq!(create.kind, GeneratedFileChangeKind::Create);
        assert!(!path.exists());
        assert!(create.diff.contains("+desired"));

        fs::write(&path, b"current\n").expect("fixture should be written");
        let update = inspect_generated_file(&path, b"desired\n").expect("inspection should work");
        assert_eq!(update.kind, GeneratedFileChangeKind::Update);
        assert!(update.diff.contains("-current"));
        assert!(update.diff.contains("+desired"));
        assert_eq!(
            fs::read(&path).expect("fixture should remain"),
            b"current\n"
        );

        let unchanged =
            inspect_generated_file(&path, b"current\n").expect("inspection should work");
        assert_eq!(unchanged.kind, GeneratedFileChangeKind::Unchanged);
        assert!(unchanged.diff.is_empty());
    }
}
