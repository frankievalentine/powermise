use std::{path::Path, process::Command};

fn compile_selection(repository: &Path) -> std::process::Output {
    Command::new(env!("CARGO_BIN_EXE_powermise"))
        .current_dir(repository)
        .args([
            "selection",
            "compile",
            "--selection",
            "selections/engineering-agents.toml",
            "--target",
            "darwin",
        ])
        .output()
        .expect("powermise should execute")
}

#[test]
fn selection_compile_emits_a_deterministic_owned_artifact() {
    let repository = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");

    let first = compile_selection(&repository);
    let second = compile_selection(&repository);

    assert!(
        first.status.success(),
        "compile failed: {}",
        String::from_utf8_lossy(&first.stderr)
    );
    assert_eq!(first.stdout, second.stdout);

    let output = String::from_utf8(first.stdout).expect("compiled artifact should be UTF-8");
    assert!(output.starts_with(
        "# Generated by Powermise. Source selection: engineering-agents. Do not edit.\n"
    ));
    assert!(output.contains("# selection_sha256 = \""));
    assert!(output.contains("# registry_sha256 = \""));
    assert!(output.contains("\n[tools]\n"));
    assert!(output.contains("\n[bootstrap.packages]\n"));
}
